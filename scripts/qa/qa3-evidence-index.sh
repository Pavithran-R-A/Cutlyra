#!/usr/bin/env bash
# qa3-evidence-index.sh — derive the audit trail for a physical QA evidence dir.
#
# Reads `<evidence>/RESULTS.md`, and from the ACTUAL matrix rows writes:
#   <evidence>/EVIDENCE_INDEX.md   every file, its size and SHA-256
#   <evidence>/QA_SUMMARY.json     the case rows plus totals computed from them
#
# Totals are never hand-written: change a result in RESULTS.md and the counts
# follow. Anything that is neither PASS nor PARTIAL (FAIL, BLOCKED, NEEDS
# EVIDENCE, …) is counted as not-passed so the summary cannot flatter the run.
#
#   bash scripts/qa/qa3-evidence-index.sh qa3-evidence-poco-20261118
#
# Read-only apart from the two files it writes inside the evidence directory.
set -euo pipefail

EVIDENCE_DIR="${1:-}"
if [ -z "$EVIDENCE_DIR" ] || [ ! -f "$EVIDENCE_DIR/RESULTS.md" ]; then
	echo "usage: $0 <evidence-dir containing RESULTS.md>" >&2
	exit 2
fi

cd "$EVIDENCE_DIR"

RESULT_ROWS=$(awk -F'|' '
	# Matrix rows look like: | 3 | Rotation ... | **PARTIAL** | `49`, `26` |
	/^\|[[:space:]]*[0-9]+[[:space:]]*\|/ {
		id = $2; name = $3; verdict = $4; evidence = $5
		gsub(/^[[:space:]]+|[[:space:]]+$/, "", id)
		gsub(/^[[:space:]]+|[[:space:]]+$/, "", name)
		gsub(/^[[:space:]]+|[[:space:]]+$/, "", verdict)
		gsub(/^[[:space:]]+|[[:space:]]+$/, "", evidence)
		gsub(/\*/, "", verdict)
		# Keep the qualifier text but split the leading classification.
		classification = verdict
		sub(/[[:space:]]*\(.*$/, "", classification)
		printf "%s\t%s\t%s\t%s\n", id, classification, name, evidence
	}
' RESULTS.md)

if [ -z "$RESULT_ROWS" ]; then
	echo "no matrix rows parsed from RESULTS.md — refusing to emit an empty summary" >&2
	exit 1
fi

TOTAL=$(printf '%s\n' "$RESULT_ROWS" | wc -l | tr -d ' ')
PASS=$(printf '%s\n' "$RESULT_ROWS" | awk -F'\t' '$2 == "PASS"' | wc -l | tr -d ' ')
PARTIAL=$(printf '%s\n' "$RESULT_ROWS" | awk -F'\t' '$2 == "PARTIAL"' | wc -l | tr -d ' ')
FAIL=$(printf '%s\n' "$RESULT_ROWS" | awk -F'\t' '$2 == "FAIL"' | wc -l | tr -d ' ')
BLOCKED=$(printf '%s\n' "$RESULT_ROWS" | awk -F'\t' '$2 == "BLOCKED"' | wc -l | tr -d ' ')
NOT_PASSED=$((TOTAL - PASS))
GENERATED_AT="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

# ---------------------------------------------------------------- file index
{
	echo "# QA3 evidence index — POCO M4 Pro 5G, 2026-11-18"
	echo
	echo "Generated by \`scripts/qa/qa3-evidence-index.sh\` at ${GENERATED_AT} (UTC)."
	echo "Every file in this directory is listed with its byte size and SHA-256 so a"
	echo "reviewer can confirm the screenshots and the export are the ones the report"
	echo "describes. Regenerate after adding evidence; never edit by hand."
	echo
	echo "**The raw files are deliberately not committed.** This repository keeps"
	echo "device evidence on disk and versions the report and this index; the"
	echo "screenshots, screen dumps and the exported MP4 stay untracked, exactly"
	echo "like the existing \`qa-final-*\` evidence directories. The hashes below"
	echo "are what make the uncommitted files auditable."
	echo
	echo "## Matrix totals (computed from the RESULTS.md rows)"
	echo
	echo "| Classification | Rows |"
	echo "|---|---|"
	echo "| TOTAL | ${TOTAL} |"
	echo "| PASS | ${PASS} |"
	echo "| PARTIAL | ${PARTIAL} |"
	echo "| FAIL | ${FAIL} |"
	echo "| BLOCKED | ${BLOCKED} |"
	echo "| not fully passed (TOTAL − PASS) | ${NOT_PASSED} |"
	echo
	echo "## Files"
	echo
	echo "| File | Bytes | SHA-256 |"
	echo "|---|---|---|"
	find . -type f ! -name 'EVIDENCE_INDEX.md' ! -name 'QA_SUMMARY.json' -print0 |
		sort -z |
		while IFS= read -r -d '' file; do
			path="${file#./}"
			bytes=$(wc -c <"$file" | tr -d ' ')
			digest=$(sha256sum "$file" | cut -d' ' -f1)
			printf '| `%s` | %s | `%s` |\n' "$path" "$bytes" "$digest"
		done
} >EVIDENCE_INDEX.md

# ------------------------------------------------------------- QA_SUMMARY.json
{
	printf '{\n'
	printf '  "generatedAt": "%s",\n' "$GENERATED_AT"
	printf '  "generatedBy": "scripts/qa/qa3-evidence-index.sh",\n'
	printf '  "device": {\n'
	printf '    "model": "POCO M4 Pro 5G (22031116AI, evergo_p_in)",\n'
	printf '    "serial": "CIUWEMJBPBDUWC7D",\n'
	printf '    "os": "Android 13 (API 33), MIUI V816"\n'
	printf '  },\n'
	printf '  "package": "app.cutlyra.editor.qa3",\n'
	printf '  "versionName": "0.1.1",\n'
	printf '  "versionCode": 2,\n'
	printf '  "matrix": {\n'
	printf '    "total": %s,\n' "$TOTAL"
	printf '    "pass": %s,\n' "$PASS"
	printf '    "partial": %s,\n' "$PARTIAL"
	printf '    "fail": %s,\n' "$FAIL"
	printf '    "blocked": %s,\n' "$BLOCKED"
	printf '    "notFullyPassed": %s\n' "$NOT_PASSED"
	printf '  },\n'
	printf '  "cases": [\n'
	printf '%s\n' "$RESULT_ROWS" | awk -F'\t' '
		{
			# Escape the two characters that can break the JSON string.
			gsub(/\\/, "\\\\", $3); gsub(/"/, "\\\"", $3)
			gsub(/\\/, "\\\\", $4); gsub(/"/, "\\\"", $4)
			printf "    {\"id\": %s, \"result\": \"%s\", \"name\": \"%s\", \"evidence\": \"%s\"}%s\n", $1, $2, $3, $4, (NR == total ? "" : ",")
		}' total="$TOTAL"
	printf '  ]\n'
	printf '}\n'
} >QA_SUMMARY.json

# Every case row must be accounted for exactly once.
if command -v bun >/dev/null 2>&1; then
	bun -e "
		const s = require('./QA_SUMMARY.json');
		if (s.cases.length !== s.matrix.total) {
			console.error('QA_SUMMARY.json: cases.length ' + s.cases.length + ' != matrix.total ' + s.matrix.total);
			process.exit(1);
		}
	"
fi

echo "wrote EVIDENCE_INDEX.md and QA_SUMMARY.json (${TOTAL} rows: ${PASS} PASS, ${PARTIAL} PARTIAL, ${FAIL} FAIL, ${BLOCKED} BLOCKED)"
