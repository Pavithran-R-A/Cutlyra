/** Type guard for category ids coming from strings (chips, stored prefs). */
export function isTemplateCategory(value: string): value is TemplateCategory {
	return value in TEMPLATE_CATEGORIES;
}

export function getTemplate({ id }: { id: string }): Template | null {
	return TEMPLATES.find((template) => template.id === id) ?? null;
}

export function templatesForCategory({
	category,
}: {
	category: TemplateCategory | "all";
}): Template[] {
	if (category === "all") return [...TEMPLATES];
	return TEMPLATES.filter((template) => template.category === category);
}
