import type { Template, TemplateCategory } from "./types";

/**
 * The shipped template library.
 *
 * Everything here is data: no bundled video, no licensed music, no network
 * fetch, no per-template code. Each template is a handful of main-track media
 * slots the user fills from their own gallery plus text slots they can edit,
 * on a canvas the engine already exports. A template therefore cannot go stale
 * against the exporter, and adding the thirteenth one is a data edit.
 *
 * `duration` is the timeline the template promises; media slots are contiguous
 * and must fit inside it (tests/template-library.test.ts enforces both).
 */

