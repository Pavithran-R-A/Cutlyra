package app.cutlyra.editor.export

/**
 * The Android half of the shared chroma-key model.
 *
 * Mirrors `packages/editor-core/src/effects/chroma-key.ts` line for line: the
 * same panel units (`keyColor` `#rrggbb`, similarity/softness/spill 0..100),
 * the same Rec.709 Cb/Cr distance, the same `MAX_CHROMA_DISTANCE = 0.6` scale.
 * `EdlChromaKeyEffect` owns only the GL plumbing; every number it uploads comes
 * from [uniforms] below, so preview and export cannot key with different
 * colours or thresholds.
 *
 * The distance is measured on the Cb/Cr plane rather than in RGB because a lit
 * green screen is never one RGB value: its luma moves, its chroma barely does.
 * Keying on chroma removes shadowed screen while keeping a red/blue subject
 * (a very different chroma angle) intact.
 *
 * `alpha()` is the reference implementation the GLSL pass mirrors; the JVM test
 * pins it against values generated by the TypeScript implementation.
 */
data class ChromaKeyUniforms(
    val keyR: Float,
    val keyG: Float,
    val keyB: Float,
    /** Distance on the Cb/Cr plane that still counts as background. */
    val similarity: Float,
    /** Width of the soft edge, in the same distance units. */
    val softness: Float,
    /** 0..1 green-excess removal. */
    val spill: Float,
) {
    fun key(): FloatArray = floatArrayOf(keyR, keyG, keyB)
}

object ChromaKeyMath {
    const val CHROMA_KEY_TYPE = "chroma-key"

    /** Largest Cb/Cr distance the similarity slider can reach (see TS model). */
    const val MAX_CHROMA_DISTANCE = 0.6f

    private const val LUMA_R = 0.2126f
    private const val LUMA_G = 0.7152f
    private const val LUMA_B = 0.0722f
    private const val CB_SCALE = 1.8556f
    private const val CR_SCALE = 1.5748f

    /** Params the shader reads. Anything else is refused, never ignored. */
    val SUPPORTED_PARAMS: Set<String> = setOf("keyColor", "similarity", "softness", "spill")

    /** `#00b140` — `DEFAULT_CHROMA_KEY.keyColor` in TypeScript. */
    private val DEFAULT_KEY = floatArrayOf(0f, 177f / 255f, 64f / 255f)

    fun parseHexColor(hex: String?): FloatArray {
        val match = hex?.trim()?.removePrefix("#") ?: return DEFAULT_KEY.copyOf()
        val expanded = when (match.length) {
            3 -> match.map { "$it$it" }.joinToString("")
            6 -> match
            else -> return DEFAULT_KEY.copyOf()
        }
        val value = expanded.toIntOrNull(16) ?: return DEFAULT_KEY.copyOf()
        return floatArrayOf(
            ((value shr 16) and 0xFF) / 255f,
            ((value shr 8) and 0xFF) / 255f,
            (value and 0xFF) / 255f,
        )
    }

    private fun number(params: Map<String, Any?>, key: String, fallback: Float): Float {
        val raw = params[key] ?: return fallback
        val value = (raw as? Number)?.toFloat() ?: return fallback
        if (!value.isFinite()) return fallback
        return value.coerceIn(0f, 100f)
    }

    /** Effect params -> shader units, defaults identical to the TS model. */
    fun uniforms(params: Map<String, Any?>): ChromaKeyUniforms {
        val key = parseHexColor(params["keyColor"] as? String)
        return ChromaKeyUniforms(
            keyR = key[0],
            keyG = key[1],
            keyB = key[2],
            similarity = number(params, "similarity", 30f) / 100f * MAX_CHROMA_DISTANCE,
            softness = number(params, "softness", 8f) / 100f * MAX_CHROMA_DISTANCE,
            spill = number(params, "spill", 60f) / 100f,
        )
    }

    private fun chroma(rgb: FloatArray): FloatArray {
        val luma = LUMA_R * rgb[0] + LUMA_G * rgb[1] + LUMA_B * rgb[2]
        return floatArrayOf((rgb[2] - luma) / CB_SCALE, (rgb[0] - luma) / CR_SCALE)
    }

    /** The shader's alpha for one 0..1 RGB pixel (reference implementation). */
    fun alpha(rgb: FloatArray, uniforms: ChromaKeyUniforms): Float {
        val key = chroma(uniforms.key())
        val pixel = chroma(rgb)
        val dx = pixel[0] - key[0]
        val dy = pixel[1] - key[1]
        val distance = kotlin.math.sqrt(dx * dx + dy * dy)
        val edge = maxOf(uniforms.softness, 1e-4f)
        val t = ((distance - uniforms.similarity) / edge).coerceIn(0f, 1f)
        return t * t * (3f - 2f * t)
    }

    /** Green channel after spill reduction (the shader's RGB output). */
    fun spillGreen(rgb: FloatArray, spill: Float): Float {
        val excess = maxOf(0f, rgb[1] - maxOf(rgb[0], rgb[2]))
        return maxOf(0f, rgb[1] - excess * spill.coerceIn(0f, 1f))
    }
}
