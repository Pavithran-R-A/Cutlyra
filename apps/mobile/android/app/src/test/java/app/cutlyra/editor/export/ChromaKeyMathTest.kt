package app.cutlyra.editor.export

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Pins the Android chroma-key numbers to the TypeScript model
 * (`packages/editor-core/src/effects/chroma-key.ts`).
 *
 * The expected values below were produced by the TS implementation itself, so a
 * change to either side that is not mirrored in the other fails here in CI
 * instead of shipping an export whose key does not match the preview.
 */
class ChromaKeyMathTest {
    private val green = floatArrayOf(0f, 177f / 255f, 64f / 255f)
    private val red = floatArrayOf(1f, 0f, 0f)
    private val blue = floatArrayOf(0f, 0f, 1f)

    @Test
    fun defaultsMatchTheTypeScriptDefaults() {
        val uniforms = ChromaKeyMath.uniforms(emptyMap())
        assertEquals(0f, uniforms.keyR, 1e-6f)
        assertEquals(177f / 255f, uniforms.keyG, 1e-6f)
        assertEquals(64f / 255f, uniforms.keyB, 1e-6f)
        assertEquals(0.18f, uniforms.similarity, 1e-6f)
        assertEquals(0.048f, uniforms.softness, 1e-6f)
        assertEquals(0.6f, uniforms.spill, 1e-6f)
    }

    @Test
    fun parsesHexAndFallsBackToGreen() {
        assertEquals(1f, ChromaKeyMath.parseHexColor("#f00")[0], 1e-6f)
        assertEquals(0f, ChromaKeyMath.parseHexColor("#f00")[1], 1e-6f)
        assertEquals(1f, ChromaKeyMath.parseHexColor("#00ff00")[1], 1e-6f)
        assertEquals(177f / 255f, ChromaKeyMath.parseHexColor("nope")[1], 1e-6f)
        assertEquals(0f, ChromaKeyMath.parseHexColor(null)[0], 1e-6f)
    }

    @Test
    fun clampsSliderInputLikeTheTypeScriptModel() {
        val uniforms = ChromaKeyMath.uniforms(
            mapOf("keyColor" to "00ff00", "similarity" to 999, "softness" to -4, "spill" to "x"),
        )
        assertEquals(ChromaKeyMath.MAX_CHROMA_DISTANCE, uniforms.similarity, 1e-6f)
        assertEquals(0f, uniforms.softness, 1e-6f)
        // Missing/non-numeric spill keeps the default (0.6), as in TS.
        assertEquals(0.6f, uniforms.spill, 1e-6f)
    }

    @Test
    fun alphaKeysTheScreenOutAndKeepsSubjects() {
        val uniforms = ChromaKeyMath.uniforms(emptyMap())
        assertEquals(0f, ChromaKeyMath.alpha(green, uniforms), 1e-5f)
        assertEquals(1f, ChromaKeyMath.alpha(red, uniforms), 1e-5f)
        assertEquals(1f, ChromaKeyMath.alpha(blue, uniforms), 1e-5f)
        // A grey shadow on the screen keeps ~all of its luma change.
        assertTrue(ChromaKeyMath.alpha(floatArrayOf(0.25f, 0.3f, 0.25f), uniforms) > 0.9f)
    }

    /** Values generated by the TS `chromaKeyAlpha` reference implementation. */
    @Test
    fun alphaMatchesTheTypeScriptReferenceOnASpread() {
        val uniforms = ChromaKeyMath.uniforms(
            mapOf("keyColor" to "#00b140", "similarity" to 30, "softness" to 8, "spill" to 60),
        )
        val samples = listOf(
            floatArrayOf(0f, 0.694f, 0.251f) to 0f,
            floatArrayOf(0.05f, 0.6f, 0.2f) to 0f,
            // Just past the threshold: the soft ramp leaves it partly opaque.
            floatArrayOf(0.3f, 0.6f, 0.3f) to 0.16379f,
            floatArrayOf(0.5f, 0.5f, 0.5f) to 1f,
            floatArrayOf(1f, 0f, 0f) to 1f,
            floatArrayOf(0f, 0f, 1f) to 1f,
            floatArrayOf(0.2f, 0.5f, 0.3f) to 0.406831f,
            floatArrayOf(0.6f, 0.7f, 0.4f) to 1f,
        )
        for ((rgb, expected) in samples) {
            assertEquals(
                "alpha for rgb(${rgb.joinToString()})",
                expected,
                ChromaKeyMath.alpha(rgb, uniforms),
                1e-3f,
            )
        }
    }

    @Test
    fun spillPullsGreenTowardTheOtherChannels() {
        assertEquals(0.6f, ChromaKeyMath.spillGreen(floatArrayOf(0.6f, 0.9f, 0.5f), 1f), 1e-6f)
        assertEquals(0f, ChromaKeyMath.spillGreen(red, 1f), 1e-6f)
        assertEquals(0.8f, ChromaKeyMath.spillGreen(floatArrayOf(0.2f, 0.8f, 0.2f), 0f), 1e-6f)
    }
}
